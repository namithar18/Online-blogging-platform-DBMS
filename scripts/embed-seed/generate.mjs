// =====================================================================
// generate.mjs — turns each post into a 384-number embedding.
//
// Two modes:
//   1. node generate.mjs
//        Reads every post from DATABASE_URL and writes
//        db/seed_embeddings.sql (one INSERT row per post). That file is
//        committed, so loading embeddings needs only psql, not this script.
//   2. node generate.mjs --query "how do databases find rows quickly"
//        Embeds the phrase and prints a ready-to-run semantic search query.
//        Needs no database connection; pipe the output into psql.
//
// Setup (once):  cd scripts/embed-seed && npm install
// The first run downloads the model (~90 MB) into a local cache.
// =====================================================================

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { pipeline } from '@huggingface/transformers';

// Stored in post_embeddings.model_name: part of the primary key, so a
// second model can be added later without overwriting these vectors.
const MODEL_NAME = 'all-MiniLM-L6-v2';
// ONNX build of the same model, runnable from Node (no Python needed).
const HF_MODEL = 'Xenova/all-MiniLM-L6-v2';
const DIMENSIONS = 384;   // must match vector(384) in schema.sql (C6)

const OUTPUT_FILE = fileURLToPath(new URL('../../db/seed_embeddings.sql', import.meta.url));

// The text that represents a post. The app must embed new posts the same
// way, or their vectors would not be comparable with these.
function postText(post) {
  return `${post.title}. ${post.content}`;
}

// mean pooling + normalize: one vector per text, scaled to length 1, so
// cosine distance (<=>) compares direction only.
async function embed(texts) {
  const extractor = await pipeline('feature-extraction', HF_MODEL, { dtype: 'fp32' });
  const output = await extractor(texts, { pooling: 'mean', normalize: true });
  const vectors = output.tolist();
  for (const v of vectors) {
    if (v.length !== DIMENSIONS) {
      throw new Error(`Expected ${DIMENSIONS} dimensions, got ${v.length}`);
    }
  }
  return vectors;
}

// pgvector's text format: '[0.1,0.2,...]'. Six decimals is far more
// precision than the similarity ranking needs and keeps the file small.
function toVectorLiteral(v) {
  return `'[${v.map((x) => x.toFixed(6)).join(',')}]'`;
}

async function generateSeedFile() {
  if (!process.env.DATABASE_URL) {
    console.error('Set DATABASE_URL, e.g. postgresql://postgres:postgres@localhost:5432/blog');
    process.exit(1);
  }

  const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
  await client.connect();
  // Every post gets an embedding, drafts included: C7 is applied when
  // searching (through published_posts), not when storing.
  const { rows: posts } = await client.query(
    'SELECT post_id, title, content FROM posts ORDER BY post_id'
  );
  await client.end();

  const vectors = await embed(posts.map(postText));

  const values = posts
    .map((post, i) => {
      const title = post.title.replace(/\n/g, ' ');
      return `    -- ${post.post_id}. ${title}\n` +
             `    (${post.post_id}, '${MODEL_NAME}', ${toVectorLiteral(vectors[i])})`;
    })
    .join(',\n');

  const sql = `-- =====================================================================
-- seed_embeddings.sql — GENERATED by scripts/embed-seed/generate.mjs.
-- Do not edit by hand; re-run the script after changing seed posts.
--
-- One ${MODEL_NAME} embedding (${DIMENSIONS} dimensions) per seed post,
-- computed from "title. content". The post_ids assume seed.sql was loaded
-- (it restarts ids at 1).
--
-- Run after seed.sql:
--   psql "$DATABASE_URL" -f db/seed_embeddings.sql
-- =====================================================================

\\set ON_ERROR_STOP on

BEGIN;

-- Upsert: on a re-run the (post_id, model_name) primary key already
-- exists, so the row is updated instead of failing on the duplicate.
INSERT INTO post_embeddings (post_id, model_name, embedding) VALUES
${values}
ON CONFLICT (post_id, model_name)
DO UPDATE SET embedding  = EXCLUDED.embedding,
              created_at = now();

COMMIT;

\\echo '=== post_embeddings: ${posts.length} rows of ${DIMENSIONS} dimensions expected ==='
SELECT count(*) AS embeddings, min(vector_dims(embedding)) AS dimensions
FROM post_embeddings
WHERE model_name = '${MODEL_NAME}';
`;

  writeFileSync(OUTPUT_FILE, sql);
  console.log(`Wrote ${posts.length} embeddings to ${OUTPUT_FILE}`);
}

async function printSearchQuery(phrase) {
  const [vector] = await embed([phrase]);
  const comment = phrase.replace(/\n/g, ' ');
  // Same shape as the query the app will run: C7 via published_posts,
  // smallest cosine distance first.
  console.log(`-- Semantic search for: ${comment}
SELECT p.post_id,
       p.title,
       round((e.embedding <=> q.v)::numeric, 4) AS cosine_distance
FROM published_posts p
JOIN post_embeddings e ON e.post_id = p.post_id AND e.model_name = '${MODEL_NAME}'
CROSS JOIN (SELECT ${toVectorLiteral(vector)}::vector(${DIMENSIONS}) AS v) AS q
ORDER BY e.embedding <=> q.v
LIMIT 5;`);
}

const queryFlag = process.argv.indexOf('--query');
if (queryFlag !== -1) {
  const phrase = process.argv[queryFlag + 1];
  if (!phrase) {
    console.error('Usage: node generate.mjs --query "your search phrase"');
    process.exit(1);
  }
  await printSearchQuery(phrase);
} else {
  await generateSeedFile();
}
